"""Zips the Source project for backup or for sharing.

    python tools/backup_source.py            full backup  -> ../Source-backup.zip
    python tools/backup_source.py --share    smaller: also leaves out .agent/archive (old plans and reports)
    python tools/backup_source.py --stamp    adds the date and time to the name (keeps older zips)
    python tools/backup_source.py --out DIR  puts the zip in DIR instead of next to Source

Inside the zip everything is under one top folder, Source-backup/, as before.

Left out always: node_modules and .git (node_modules/INSTALLED_PACKAGES.txt lists the installed versions instead),
dist/ (build output), .dev-data/ and Xplayer-Data/ (your library and settings, which can hold an AI key), the files
tools/dev/gen-web.js generates (src/player.js, src/music_player.html, src/fonts, src/icons), and caches.
Only the standard library is used. The zip is written under a temporary name and replaces the old one when it is complete.
"""

import argparse
import json
import os
import sys
import zipfile
from datetime import datetime
from pathlib import Path

TOP = "Source-backup"

# Folder names skipped wherever they appear.
SKIP_DIRS = {"node_modules", ".git", "__pycache__", ".dev-data", "Xplayer-Data", "dist", ".vite", ".cache"}
# Paths (relative to Source, forward slashes) skipped: generated by tools/dev/gen-web.js.
SKIP_PATHS = {"src/player.js", "src/music_player.html", "src/fonts", "src/icons"}
SKIP_SHARE = {".agent/archive"}
SKIP_FILES = {".DS_Store", "Thumbs.db"}
SKIP_SUFFIXES = (".pyc", ".log", ".tmp")


def find_source():
    """Source is the nearest parent folder (of this file) that has a package.json."""
    here = Path(__file__).resolve().parent
    for folder in [here, *here.parents]:
        if (folder / "package.json").exists():
            return folder
    raise FileNotFoundError("Could not find Source (a parent folder with package.json).")


def installed_version(source, name):
    try:
        data = json.loads((source / "node_modules" / name / "package.json").read_text(encoding="utf-8"))
        return data.get("version", "UNKNOWN")
    except FileNotFoundError:
        return "NOT INSTALLED"
    except Exception as error:
        return f"ERROR: {error}"


def package_manifest(source):
    package = json.loads((source / "package.json").read_text(encoding="utf-8"))
    lines = [
        "Lightweight backup of the Source project.",
        "",
        "node_modules and .git were intentionally left out.",
        "This file lists the top-level npm packages installed in Source when the backup was made.",
        f"Made: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        f"Project: {package.get('name', '?')} {package.get('version', '?')}",
        "",
    ]
    for section in ("dependencies", "devDependencies", "optionalDependencies"):
        packages = package.get(section, {})
        if not packages:
            continue
        lines += [section + ":", "-" * len(section)]
        lines += [f"{name} {installed_version(source, name)}" for name in sorted(packages)]
        lines.append("")
    return "\n".join(lines)


def wanted_files(source, share):
    skip_paths = SKIP_PATHS | (SKIP_SHARE if share else set())
    for folder, dirs, files in os.walk(source):
        relative_folder = Path(folder).relative_to(source).as_posix()
        relative_folder = "" if relative_folder == "." else relative_folder
        kept = []
        for name in dirs:
            relative = f"{relative_folder}/{name}" if relative_folder else name
            if name in SKIP_DIRS or relative in skip_paths:
                continue
            kept.append(name)
        dirs[:] = sorted(kept)
        for name in sorted(files):
            relative = f"{relative_folder}/{name}" if relative_folder else name
            if name in SKIP_FILES or name.endswith(SKIP_SUFFIXES) or relative in skip_paths:
                continue
            if name.startswith("Source-backup") and name.endswith(".zip"):
                continue
            path = Path(folder) / name
            if path.is_file():  # skips broken links and the like
                yield path, relative


def human(size):
    for unit in ("B", "KB", "MB", "GB"):
        if size < 1024 or unit == "GB":
            return f"{size:.0f} {unit}" if unit == "B" else f"{size:.1f} {unit}"
        size /= 1024


def main():
    parser = argparse.ArgumentParser(description="Zip the Source project for backup or sharing.")
    parser.add_argument("--share", action="store_true", help="also leave out .agent/archive")
    parser.add_argument("--stamp", action="store_true", help="add the date and time to the zip name")
    parser.add_argument("--out", help="folder for the zip (default: next to Source)")
    args = parser.parse_args()

    source = find_source()
    out_dir = Path(args.out).resolve() if args.out else source.parent
    out_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("-%Y%m%d-%H%M") if args.stamp else ""
    target = out_dir / f"{TOP}{stamp}.zip"
    temp = out_dir / f"{TOP}{stamp}.zip.partial"

    print("Source backup tool")
    print("==================")
    print(f"Source: {source}")
    print(f"Mode:   {'share (without .agent/archive)' if args.share else 'full'}")
    print()

    count, total, biggest = 0, 0, []
    try:
        with zipfile.ZipFile(temp, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
            for path, relative in wanted_files(source, args.share):
                size = path.stat().st_size
                archive.write(path, f"{TOP}/{relative}")
                count += 1
                total += size
                biggest.append((size, relative))
            archive.writestr(f"{TOP}/node_modules/INSTALLED_PACKAGES.txt", package_manifest(source))
        temp.replace(target)
    except BaseException:
        if temp.exists():
            temp.unlink()
        raise

    print(f"{count} files, {human(total)} before compression")
    print(f"Backup: {target} ({human(target.stat().st_size)})")
    print()
    print("Largest files:")
    for size, relative in sorted(biggest, reverse=True)[:5]:
        print(f"  {human(size):>9}  {relative}")
    print()
    print("Left out: node_modules, .git, dist, .dev-data, Xplayer-Data, generated page files, caches")
    print("Recorded: node_modules/INSTALLED_PACKAGES.txt")


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"\nBackup failed: {error}", file=sys.stderr)
        sys.exit(1)