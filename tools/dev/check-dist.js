'use strict';

// Checks the portable folder that `npm run dist` makes (dist/Xplayer): the files the app needs are in it, the ones that should not
// ship are not. The Windows build job in .github/workflows/build.yml runs it after the build; run it by hand the same way.
//
//   node tools/dev/check-dist.js [<dist/Xplayer folder>]
//
// electron-builder is set to asar:false (package.json > build), so the app is plain files under resources/app.

const fs = require('fs');
const path = require('path');

const MUST_EXIST = [
    'Xplayer.exe',
    'portable.txt',
    'resources/app/package.json',
    'resources/app/electron/main.js',
    'resources/app/electron/preload.js',
    'resources/app/electron/app-paths.js',
    'resources/app/src/ui-next/index.html',
    'resources/app/src/music_player.html', // generated by gen-web.js: the build runs it first
    'resources/app/src/player.js',
    'resources/app/src/assets/app-icon/xplayer.ico',
    'resources/app/node_modules/music-metadata/package.json',
    'resources/app/node_modules/node-taglib-sharp/package.json'
];

// Things the build leaves out on purpose (package.json > build.files), and the person's data, which is never part of a build.
const MUST_NOT_EXIST = ['Xplayer-Data', 'resources/app/src/old-ui', 'resources/app/src/ui-next/dev', 'resources/app/.dev-data', 'resources/app/tools'];

function checkDist(dir, exists = fs.existsSync) {
    const problems = [];
    if (!exists(dir)) return [`${dir} does not exist (run npm run dist first)`];
    for (const rel of MUST_EXIST) if (!exists(path.join(dir, ...rel.split('/')))) problems.push(`missing: ${rel}`);
    for (const rel of MUST_NOT_EXIST) if (exists(path.join(dir, ...rel.split('/')))) problems.push(`should not be there: ${rel}`);
    return problems;
}

if (require.main === module) {
    const dir = path.resolve(process.argv[2] || path.join(__dirname, '..', '..', 'dist', 'Xplayer'));
    const problems = checkDist(dir);
    if (problems.length) {
        console.error(`check-dist: ${dir}\n  ` + problems.join('\n  '));
        process.exit(1);
    }
    console.log(`check-dist: ${dir} looks right (${MUST_EXIST.length} files present, ${MUST_NOT_EXIST.length} absent as intended)`);
}

module.exports = { checkDist, MUST_EXIST, MUST_NOT_EXIST };
