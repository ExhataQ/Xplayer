import { fileURLToPath } from 'node:url';
import { ICONS } from '../src/ui-next/icons/icons.js';
const EXTRA = {
  'trash': '<path d="M3 6h18"/><path d="M19 6v14c0 1-1 2-2 2H7c-1 0-2-1-2-2V6"/><path d="M8 6V4c0-1 1-2 2-2h4c1 0 2 1 2 2v2"/><path d="M10 11v6"/><path d="M14 11v6"/>',
  'pencil': '<path d="M21.174 6.812a1 1 0 0 0-3.986-3.987L3.842 16.174a2 2 0 0 0-.5.83l-1.321 4.352a.5.5 0 0 0 .623.622l4.353-1.32a2 2 0 0 0 .83-.497z"/><path d="m15 5 4 4"/>',
  'share': '<path d="m15 14 5-5-5-5"/><path d="M4 20v-7a4 4 0 0 1 4-4h12"/>',
  'folder-open': '<path d="m6 14 1.5-2.9A2 2 0 0 1 9.24 10H20a2 2 0 0 1 1.94 2.5l-1.54 6a2 2 0 0 1-1.95 1.5H4a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h3.9a2 2 0 0 1 1.69.9l.81 1.2a2 2 0 0 0 1.67.9H18a2 2 0 0 1 2 2v2"/>',
  'folder-minus': '<path d="M9 13h6"/><path d="M20 20a2 2 0 0 0 2-2V8a2 2 0 0 0-2-2h-7.9a2 2 0 0 1-1.69-.9L9.6 3.9A2 2 0 0 0 7.93 3H4a2 2 0 0 0-2 2v13a2 2 0 0 0 2 2Z"/>',
  'chart': '<path d="M18 20V10"/><path d="M12 20V4"/><path d="M6 20v-6"/>',
  'music': '<path d="M9 18V5l12-2v13"/><circle cx="6" cy="18" r="3"/><circle cx="18" cy="16" r="3"/>',
  'pause': '<rect x="14" y="4" width="4" height="16" rx="1"/><rect x="6" y="4" width="4" height="16" rx="1"/>'
};
const SRC = (n) => EXTRA[n] ?? ICONS[n];
// Font Awesome class -> icon name
const MAP = [
  ['fa-plus', 'plus'], ['fa-plus-square', 'plus'], ['fa-heart', 'heart'], ['fa-list', 'list-music'], ['fa-align-left', 'text-align-start'],
  ['fa-info-circle', 'info'], ['fa-folder-open', 'folder-open'], ['fa-folder', 'folder'], ['fa-folder-minus', 'folder-minus'],
  ['fa-trash-alt', 'trash'], ['fa-pen', 'pencil'], ['fa-share', 'share'], ['fa-thumbtack', 'pin'], ['fa-times', 'x'], ['fa-check', 'check'],
  ['fa-chart-bar', 'chart'], ['fa-bell-slash', 'bell-off'], ['fa-cog', 'gear'], ['fa-music', 'music'], ['fa-play', 'play'], ['fa-pause', 'pause']
];
const uri = (name) => {
  const body = SRC(name);
  if (!body) throw new Error('missing icon ' + name);
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='1.75' stroke-linecap='round' stroke-linejoin='round'>${body.replace(/"/g, "'")}</svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg).replace(/%20/g, ' ').replace(/'/g, '%27')}")`;
};
// gear lives in custom-icons
import { CUSTOM_ICONS } from '../src/ui-next/icons/custom-icons.js';
EXTRA.gear = CUSTOM_ICONS.gear;
let css = `/* Static icons for the engine's context menus (task PB-07, brief 7.5).
 *
 * The engine writes <i class="fas fa-..."> in every menu item (song rows, library items, the list menu, lyrics lines). Font Awesome is not
 * loaded in ui-next, so legacy-overlays.css hides them. Here each class draws a small static icon from the app's own set (Lucide, plus a
 * few drawn for this app) with a CSS mask, so it follows the text color. Generated by tools/build-context-menu-icons.mjs: edit the generator, not this file.
 * The submenu arrow (fa-chevron-right) is drawn in legacy-overlays.css and is left alone.
 */
.context-menu .context-menu-item .fas:not(.fa-chevron-right),
.context-menu .context-menu-item .far:not(.fa-chevron-right) {
    display: inline-block;
    flex: none;
    width: 16px;
    height: 16px;
    background-color: var(--text-tertiary);
    -webkit-mask: var(--glyph) center / contain no-repeat;
    mask: var(--glyph) center / contain no-repeat;
    transition: background-color var(--duration-fast, 120ms) ease;
}
.context-menu .context-menu-item:hover .fas:not(.fa-chevron-right),
.context-menu .context-menu-item:hover .far:not(.fa-chevron-right) {
    background-color: var(--text-primary);
}
`;
for (const [cls, name] of MAP) css += `.context-menu .context-menu-item .${cls} {\n    --glyph: ${uri(name)};\n}\n`;
css += `
/* A liked song shows its heart filled in the accent color; "Add to favorites" (unliked) stays an outline. */
.context-menu .context-menu-item .fa-heart:not(.unliked) {
    background-color: var(--accent);
}
/* Delete reads as a warning: its icon and text turn red on hover. */
.context-menu .context-menu-item:hover .fa-trash-alt {
    background-color: var(--danger, #e5484d);
}
`;
const target = fileURLToPath(new URL('../src/ui-next/adapter/context-menu-icons.css', import.meta.url));
fs.writeFileSync(target, css);
console.log('wrote', target);
