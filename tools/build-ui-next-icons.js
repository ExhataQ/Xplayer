'use strict';

// Regenerates src/ui-next/icons/icons.js from the Lucide icon files (ISC license, see src/ui-next/icons/LICENSE-Lucide-ISC.txt).
// Only the icons listed in NAMES are copied, so the app never ships the whole set.
//
// Usage: node tools/build-ui-next-icons.js <folder that holds the Lucide .svg files>
//   e.g. after `npm pack lucide-static` and unpacking it: node tools/build-ui-next-icons.js path/to/package/icons
//
// To add an icon: add its Lucide file name (without .svg) to NAMES, run this, commit icons.js.

const fs = require('fs');
const path = require('path');

const NAMES = [
    'arrow-up-down',
    'bell',
    'check',
    'chevron-down',
    'chevron-left',
    'chevron-right',
    'circle-alert',
    'circle-check',
    'clock',
    'columns-3',
    'folder',
    'heart',
    'house',
    'info',
    'library',
    'list-music',
    'maximize-2',
    'minimize-2',
    'minus',
    'pause',
    'pin',
    'play',
    'plus',
    'repeat',
    'search',
    'shuffle',
    'skip-back',
    'skip-forward',
    'sliders-horizontal',
    'square',
    'tag',
    'text-align-start',
    'triangle-alert',
    'volume-2',
    'volume-x',
    'x'
];

const iconsDir = process.argv[2];
if (!iconsDir) {
    console.error('Usage: node tools/build-ui-next-icons.js <folder with the Lucide .svg files>');
    process.exit(1);
}

const entries = NAMES.map((name) => {
    const file = path.join(iconsDir, `${name}.svg`);
    if (!fs.existsSync(file)) throw new Error(`Lucide icon not found: ${file}`);
    const svg = fs.readFileSync(file, 'utf8');
    const match = svg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/);
    if (!match) throw new Error(`${file}: no <svg> element`);
    const inner = match[1]
        .split('\n')
        .map((line) => line.trim())
        .filter(Boolean)
        .join('')
        .replace(/\s*\/>/g, '/>');
    return `    ${JSON.stringify(name)}: ${JSON.stringify(inner)}`;
});

const out = `// GENERATED by tools/build-ui-next-icons.js from Lucide (ISC license, see LICENSE-Lucide-ISC.txt). Do not edit by hand.

export const ICONS = {
${entries.join(',\n')}
};

const STROKE_WIDTH = 1.75;

/**
 * Markup for one icon. Decorative by default (aria-hidden); pass \`label\` for an icon that stands alone.
 * \`filled\` fills the shape with the current text color (play, pause, heart).
 */
export function icon(name, { size = 18, filled = false, label = '' } = {}) {
    const inner = ICONS[name];
    if (!inner) throw new Error(\`Unknown icon: \${name}\`);
    const a11y = label ? \`role="img" aria-label="\${label}"\` : 'aria-hidden="true"';
    const fill = filled ? 'currentColor' : 'none';
    return \`<svg xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="\${fill}" stroke="currentColor" stroke-width="\${STROKE_WIDTH}" stroke-linecap="round" stroke-linejoin="round" \${a11y}>\${inner}</svg>\`;
}
`;

const target = path.join(__dirname, '..', 'src', 'ui-next', 'icons', 'icons.js');
fs.writeFileSync(target, out);
console.log(`Wrote ${path.relative(process.cwd(), target)} with ${NAMES.length} icons.`);
